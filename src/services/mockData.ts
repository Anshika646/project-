// Helper to generate full sections A, B, C, D for every class
function generateAllSections(): Section[] {
  const sections: Section[] = [];
  const sectionLetters = ['A', 'B', 'C', 'D'];
  const teachersPool = ['user-teacher-1', 'user-teacher-2', 'user-teacher-3', 'user-teacher-4', 'user-teacher-5', 'user-teacher-6'];

  DEMO_CLASSES.forEach((cls, idx) => {
    sectionLetters.forEach((secLetter, sIdx) => {
      const roomNum = 100 + (idx * 10) + sIdx + 1;
      const assignedTeacher = (secLetter === 'A' || secLetter === 'B') ? teachersPool[(idx + sIdx) % teachersPool.length] : null;

      sections.push({
        id: `sec-${cls.name.toLowerCase().replace(/\s+/g, '')}-${secLetter.toLowerCase()}`,
        institution_id: DEMO_INSTITUTION_ID,
        class_id: cls.id,
        name: secLetter,
        room_number: `Room ${roomNum}`,
        capacity: 35,
        class_teacher_id: assignedTeacher,
        created_at: '2025-01-01T00:00:00Z',
        updated_at: '2025-01-01T00:00:00Z',
      });
    });
  });

  return sections;
}

